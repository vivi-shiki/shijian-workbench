export function buildClassicalProsePrompt({ id, kind, title, prose }) {
  return [
    "请为下列明清文言散文（序跋、传记等）添加现代中文标点，并按现代古籍整理方式划分自然段。",
    "只允许添加、删除或调整标点与空白；不得增加、删除、替换、繁简转换任何文字，不得改异体字，不得解释、翻译或润色。",
    "句读要求：根据文意识别主谓、转折、承接、引语、书名、人名、年号和落款；正确使用逗号、句号、分号、冒号、问号、引号和书名号。不要只按固定字数断句。",
    "分段要求：序跋按论旨转换、叙事阶段、评议、作序缘起和落款划分；传记按人物身份、生平事迹、著述评价和仕履划分。段落不宜过碎，一个完整意思原则上保持在同一段。",
    "标题由外部字段保存，不要把标题重复写入正文。落款若原本属于正文则保留在最后一段，不得臆造作者。",
    "只返回 JSON 对象：{\"id\":\"原id\",\"paragraphs\":[\"第一段\",\"第二段\"]}。paragraphs 中不得出现空字符串。",
    JSON.stringify({ id, kind, title, prose })
  ].join("\n");
}
